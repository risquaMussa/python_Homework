
# Warmup 3: Boolean Expression Practice

print(not True and False)  # False because not True is False, and False and False is False.

print(True or False and False)  # True because and is evaluated first: False and False is False, then True or False is True.

print(not (5 > 3))  # False because 5 is greater than 3, so not True becomes False.

print(10 == 10 and 4 != 4)  # False because 10 == 10 is True, but 4 != 4 is False, and True and False is False.

print(not False or not True)  # True because not False is True and not True is False, so True or False is True.
